"""---

## Part 5: Similarity Search Without Labels

The nearest samples to a query, first on the raw features and then on the standardised features `Z` from Part 4.
"""

query_index = 0

dist_raw = np.linalg.norm(X - X[query_index], axis=1)
dist_z = np.linalg.norm(Z - Z[query_index], axis=1)

nearest_raw = np.argsort(dist_raw)[1:4]      # position 0 is the query itself
nearest_z = np.argsort(dist_z)[1:4]

def show(indices, title):
    print(f"\n{title}")
    print(f"{'Sample':<8}" + "".join(f"{name:>12}" for name in feature_names))
    for i in [query_index] + list(indices):
        print(f"{i:<8}" + "".join(f"{value:>12.2f}" for value in X[i]))

show(nearest_raw, "Nearest samples on raw features (first row is the query):")
show(nearest_z, "Nearest samples on standardised features (first row is the query):")

"""---

## Summary

- A sample is a vector and a dataset is a matrix; distance and cosine similarity are both built from the dot product.
- Rotation preserves distances between samples; scaling changes them, so feature scale determines which samples are similar.
- The mean follows outliers; the trimmed mean and the median are robust.
- The variance of a sample is divided by `n − 1`.
- Pearson correlation is the cosine similarity of centered features; Spearman uses ranks and is robust to outliers.
"""