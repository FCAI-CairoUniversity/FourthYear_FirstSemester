"""---

## Part 4: Covariance and Correlation

### Example 4a: Why the covariance has a sign

`cov(x, y) = Σ (xᵢ − x̄)(yᵢ − ȳ) / (n − 1)`. After centering, each sample contributes the product of its two coordinates: positive in two quadrants, negative in the other two. the net sum of these contributions determines the final sign .. observe the mean and the sign of each sample with respect to that.
"""

x = X[:, 0]    # MedIncf
y = X[:, 8]    # MedHouseVal
x_c = x - np.mean(x)
y_c = y - np.mean(y)

idx = np.random.choice(len(x), 3000, replace=False)
products = x_c[idx] * y_c[idx]

plt.figure(figsize=(9, 7))
plt.scatter(x_c[idx], y_c[idx], c=np.where(products > 0, 'cyan', 'red'), s=8, alpha=0.6)
plt.axhline(0, color='white', linewidth=1)
plt.axvline(0, color='white', linewidth=1)
plt.xlabel('MedInc - mean')
plt.ylabel('MedHouseVal - mean')
plt.title(f'Positive products (cyan): {np.mean(products > 0):.0%}    Negative products (red): {np.mean(products < 0):.0%}')
plt.grid(True, alpha=0.3)
plt.show()

"""### Example 4b: Covariance, Pearson and Spearman

The covariance is a dot product of the centered vectors. Pearson removes the units and equals the cosine similarity of the centered vectors. Spearman is Pearson computed on ranks.

(Ranking: If your raw data is $x = [45.2, 12.1, 99.5]$, you sort it and assign integer ranks: $x_{ranks} = [2, 1, 3]$. You do this independently for $y$.)
"""

n = len(x)

cov_xy = (x_c @ y_c) / (n - 1)
pearson = cov_xy / (np.std(x, ddof=1) * np.std(y, ddof=1))
cosine_centered = (x_c @ y_c) / (np.sqrt(x_c @ x_c) * np.sqrt(y_c @ y_c))
spearman = np.corrcoef(stats.rankdata(x), stats.rankdata(y))[0, 1]

print(f"Covariance:                 {cov_xy:.4f}   (np.cov: {np.cov(x, y)[0, 1]:.4f})")
print(f"Pearson:                    {pearson:.4f}   (np.corrcoef: {np.corrcoef(x, y)[0, 1]:.4f})")
print(f"Cosine of centered vectors: {cosine_centered:.4f}")
print(f"Spearman:                   {spearman:.4f}   (scipy: {stats.spearmanr(x, y)[0]:.4f})")

"""All pairwise correlations with one matrix multiplication on the standardised data `Z`."""

Z = (X - X.mean(axis=0)) / X.std(axis=0, ddof=1)      # z-score: mean 0, std 1 per feature
correlation_matrix = (Z.T @ Z) / (len(Z) - 1)         # (9, 20640) @ (20640, 9) -> (9, 9)

print(f"Equal to np.corrcoef: {np.allclose(correlation_matrix, np.corrcoef(X.T))}")

plt.figure(figsize=(10, 8))
plt.imshow(correlation_matrix, cmap='coolwarm', vmin=-1, vmax=1, aspect='auto')
plt.colorbar(label='Pearson correlation')
plt.xticks(range(len(feature_names)), feature_names, rotation=45, ha='right')
plt.yticks(range(len(feature_names)), feature_names)
for i in range(len(feature_names)):
    for j in range(len(feature_names)):
        plt.text(j, i, f'{correlation_matrix[i, j]:.2f}', ha='center', va='center', fontsize=8, color='black')
plt.title('Feature correlation matrix')
plt.tight_layout()
plt.show()

