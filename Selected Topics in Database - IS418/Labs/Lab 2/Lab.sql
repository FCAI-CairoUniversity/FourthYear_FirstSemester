-- Check if the database already exists; if not, create it
IF NOT EXISTS (SELECT * FROM sys.databases WHERE name = 'FCAI_DB')
BEGIN
    CREATE DATABASE FCAI_DB;
END
GO

-- Switch to the database
USE FCAI_DB;
GO

-- 1. Create the Partition Function
-- Defines boundaries on EnrollmentYear using RANGE LEFT (4 partitions total)
CREATE PARTITION FUNCTION PF_By_Year (DATE)
AS RANGE LEFT FOR VALUES ('2019-12-31', '2020-12-31', '2021-12-31');
GO

-- 2. Create the Partition Scheme
-- Maps each partition generated by PF_By_Year to the PRIMARY filegroup
CREATE PARTITION SCHEME PS_StudentYear
AS PARTITION PF_By_Year
ALL TO ([PRIMARY]);
GO

-- 3. Create the Partitioned Table
-- Primary key includes EnrollmentYear to maintain clustering alignment[cite: 3, 4]
CREATE TABLE Students (
    StudentID INT,
    StudentName VARCHAR(100),
    EnrollmentYear DATE,
    CONSTRAINT PK_Students PRIMARY KEY CLUSTERED (EnrollmentYear, StudentID)
) 
ON PS_StudentYear (EnrollmentYear);
GO

-- 4. Insert Sample Data
INSERT INTO dbo.Students (StudentID, StudentName, EnrollmentYear)
VALUES
(1, 'Ahmed', '2018-01-01'),
(2, 'Mona', '2019-05-10'),
(3, 'Omar', '2020-07-20'),
(4, 'Sara', '2021-11-12'),
(5, 'Youssef', '2022-03-05');
GO

-- 5. Verify Partition Distribution
-- Uses the $PARTITION function to verify which partition holds each row
SELECT 
    $PARTITION.PF_By_Year(EnrollmentYear) AS PartitionNumber,
    StudentID,
    StudentName,
    EnrollmentYear
FROM dbo.Students;
GO

-- 6. Comparison with Non-Partitioned Table

-- Create non-partitioned copy for reference
SELECT * 
INTO dbo.Students_NonPartitioned
FROM dbo.Students;
GO

-- Query non-partitioned table (SQL Server scans all rows)
SELECT * 
FROM dbo.Students_NonPartitioned
WHERE EnrollmentYear = '2020-01-01';
GO

-- Query partitioned table (SQL Server eliminates unneeded partitions)
SELECT * 
FROM dbo.Students
WHERE EnrollmentYear = '2020-01-01';
GO

